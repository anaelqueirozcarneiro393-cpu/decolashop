export function getInternationalProductsByActivatedSuppliers(activatedIds: string[]): Product[] {
  if (!activatedIds || activatedIds.length === 0 || activatedIds.includes('todos') || activatedIds.includes('all')) {
    return ALL_INTERNATIONAL_PRODUCTS;
  }
  const idSet = new Set(activatedIds.map(id => id.toLowerCase()));
  const filtered = ALL_INTERNATIONAL_PRODUCTS.filter(p => idSet.has((p.supplierId || '').toLowerCase()));
  return filtered.length > 0 ? filtered : ALL_INTERNATIONAL_PRODUCTS;
}
